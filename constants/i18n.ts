export function tFood(lang: string, name: string): string {
  const key = FOOD_KEY_MAP[name];
  if (!key) return name;
  return t(lang, key);
}

export function tFoodDesc(lang: string, name: string, fallbackDesc: string): string {
  const key = FOOD_KEY_MAP[name];
  if (!key) return fallbackDesc;
  const translated = t(lang, `${key}.desc`);
  return translated === `${key}.desc` ? fallbackDesc : translated;
}

